create table public.products (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique check (slug = lower(slug) and slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  name text not null check (char_length(btrim(name)) between 1 and 160),
  description text,
  short_description text,
  kind text not null check (kind in ('ready', 'custom')),
  status text not null default 'draft' check (status in ('draft', 'active', 'archived')),
  price numeric(12,2) not null check (price >= 0),
  compare_at_price numeric(12,2) check (compare_at_price is null or compare_at_price >= 0),
  cost_price numeric(12,2) check (cost_price is null or cost_price >= 0),
  sku text unique,
  material text,
  collection text,
  artwork_locked boolean not null default true,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.product_images (
  id uuid primary key default gen_random_uuid(),
  product_id uuid not null references public.products(id) on delete cascade,
  storage_path text not null,
  alt_text text,
  sort_order integer not null default 0,
  is_primary boolean not null default false,
  created_at timestamptz not null default now(),
  unique (product_id, storage_path)
);

create table public.phone_models (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique check (slug = lower(slug) and slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  name text not null,
  brand text not null,
  status text not null default 'active' check (status in ('active', 'inactive')),
  display_order integer not null default 0,
  base_mockup_path text,
  case_overlay_path text,
  highlight_overlay_path text,
  shadow_overlay_path text,
  print_mask_path text,
  camera_mask_path text,
  print_area jsonb not null default '{}'::jsonb,
  safe_area jsonb not null default '{}'::jsonb,
  camera_exclusion jsonb not null default '{}'::jsonb,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.product_phone_models (
  product_id uuid not null references public.products(id) on delete cascade,
  phone_model_id uuid not null references public.phone_models(id) on delete cascade,
  sku text,
  price_override numeric(12,2) check (price_override is null or price_override >= 0),
  available boolean not null default true,
  created_at timestamptz not null default now(),
  primary key (product_id, phone_model_id)
);

create table public.customers (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  phone text,
  full_name text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.addresses (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references public.customers(id) on delete cascade,
  label text,
  recipient_name text not null,
  phone text not null,
  line1 text not null,
  line2 text,
  landmark text,
  city text not null,
  state text not null,
  postal_code text not null,
  country_code text not null default 'IN' check (char_length(country_code) = 2),
  is_default boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  customer_id uuid references public.customers(id) on delete set null,
  guest_email text,
  status text not null default 'new',
  payment_status text not null default 'not_processed',
  payment_method text,
  currency text not null default 'INR' check (char_length(currency) = 3),
  subtotal numeric(12,2) not null check (subtotal >= 0),
  shipping_amount numeric(12,2) not null default 0 check (shipping_amount >= 0),
  discount_amount numeric(12,2) not null default 0 check (discount_amount >= 0),
  cod_fee numeric(12,2) not null default 0 check (cod_fee >= 0),
  total numeric(12,2) not null check (total >= 0),
  shipping_address jsonb not null,
  tracking_id text,
  courier text,
  admin_note text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (customer_id is not null or guest_email is not null)
);

create table public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  phone_model_id uuid references public.phone_models(id) on delete set null,
  product_name text not null,
  sku text,
  quantity integer not null check (quantity between 1 and 100),
  unit_price numeric(12,2) not null check (unit_price >= 0),
  fixed_design_id text,
  item_type text not null check (item_type in ('ready-design', 'custom-case')),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table public.customizations (
  id uuid primary key default gen_random_uuid(),
  order_item_id uuid not null unique references public.order_items(id) on delete cascade,
  customer_id uuid references public.customers(id) on delete set null,
  design_state jsonb not null,
  customer_upload_paths text[] not null default '{}',
  preview_path text,
  print_ready_path text,
  status text not null default 'pending' check (status in ('pending', 'approved', 'hold', 'rejected', 'printed')),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.coupons (
  id uuid primary key default gen_random_uuid(),
  code text not null check (char_length(btrim(code)) between 2 and 64),
  discount_type text not null check (discount_type in ('percentage', 'fixed')),
  value numeric(12,2) not null check (value > 0),
  minimum_cart_value numeric(12,2) not null default 0 check (minimum_cart_value >= 0),
  usage_limit integer check (usage_limit is null or usage_limit > 0),
  usage_count integer not null default 0 check (usage_count >= 0),
  starts_at timestamptz,
  ends_at timestamptz,
  active boolean not null default true,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (discount_type <> 'percentage' or value <= 100),
  check (ends_at is null or starts_at is null or ends_at > starts_at)
);
create unique index coupons_code_lower_idx on public.coupons (lower(code));

create table public.reviews (
  id uuid primary key default gen_random_uuid(),
  product_id uuid not null references public.products(id) on delete cascade,
  customer_id uuid not null references public.customers(id) on delete cascade,
  rating smallint not null check (rating between 1 and 5),
  title text,
  body text,
  status text not null default 'pending' check (status in ('pending', 'approved', 'hidden')),
  verified_purchase boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (product_id, customer_id)
);

create table public.store_settings (
