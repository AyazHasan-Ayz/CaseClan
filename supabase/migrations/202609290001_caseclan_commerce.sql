using (exists (select 1 from public.products p where p.id = product_id and p.status = 'active'));
create policy phone_models_public_read on public.phone_models for select to anon, authenticated using (status = 'active');
create policy product_phone_models_public_read on public.product_phone_models for select to anon, authenticated
using (available and exists (select 1 from public.products p where p.id = product_id and p.status = 'active') and exists (select 1 from public.phone_models m where m.id = phone_model_id and m.status = 'active'));

